"""Pydantic schemas for evaluation datasets and results."""

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Union
from datetime import datetime
from pydantic import AliasChoices, BaseModel, Field, field_validator, ConfigDict


class RAGSample(BaseModel):
    """Single evaluation sample for RAG system.
    
    Attributes:
        query: User query or question
        retrieved_docs: List of retrieved document chunks/contexts
        generated_answer: Answer generated by the RAG system
        ground_truth: Expected correct answer (optional)
        relevant_docs: List of relevant/ground truth documents (optional)
        metadata: Additional metadata (category, difficulty, etc.)
    """
    
    model_config = ConfigDict(extra="allow", populate_by_name=True)
    
    query: str = Field(..., description="User query or question")
    retrieved_docs: List[str] = Field(
        default_factory=list,
        description="Retrieved document contexts",
        validation_alias=AliasChoices("retrieved_docs", "retrieved_contexts")
    )
    generated_answer: str = Field(default="", description="Generated answer from RAG")
    ground_truth: Optional[str] = Field(None, description="Expected correct answer")
    relevant_docs: Optional[List[str]] = Field(
        None,
        description="List of relevant/ground truth documents",
        validation_alias=AliasChoices("relevant_docs", "ground_truth_contexts")
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional metadata"
    )
    
    @field_validator("query")
    @classmethod
    def validate_query(cls, v: str) -> str:
        """Validate query is not empty."""
        if not v or not v.strip():
            raise ValueError("Query cannot be empty")
        return v.strip()
    
    @field_validator("retrieved_docs")
    @classmethod
    def validate_docs(cls, v: List[str]) -> List[str]:
        """Validate and clean retrieved documents."""
        return [doc.strip() for doc in v if doc and doc.strip()]

    @field_validator("relevant_docs")
    @classmethod
    def validate_relevant_docs(cls, v: Optional[List[str]]) -> Optional[List[str]]:
        """Validate and clean relevant documents."""
        if v is None:
            return None
        cleaned = [doc.strip() for doc in v if doc and doc.strip()]
        return cleaned or None

    @property
    def retrieved_contexts(self) -> List[str]:
        """Backward-compatible alias for retrieved_docs."""
        return self.retrieved_docs

    @property
    def ground_truth_contexts(self) -> Optional[List[str]]:
        """Backward-compatible alias for relevant_docs."""
        return self.relevant_docs


# Alias for backward compatibility
EvaluationSample = RAGSample


class MetricResult(BaseModel):
    """Result from a single metric evaluation.
    
    Attributes:
        metric_name: Name of the metric
        score: Numeric score (0-1 or other range)
        passed: Whether the sample passed the metric threshold
        details: Additional details about the evaluation
        error: Error message if evaluation failed
    """
    
    model_config = ConfigDict(extra="allow", populate_by_name=True)
    
    metric_name: str = Field(..., description="Name of the metric")
    score: Optional[float] = Field(None, description="Numeric score")
    passed: Optional[bool] = Field(None, description="Pass/fail status")
    details: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional evaluation details"
    )
    error: Optional[str] = Field(None, description="Error message if failed")
    
    @field_validator("score")
    @classmethod
    def validate_score(cls, v: Optional[float]) -> Optional[float]:
        """Validate score is a valid number."""
        if v is not None and (not isinstance(v, (int, float)) or v != v):  # Check for NaN
            raise ValueError("Score must be a valid number")
        return v


class SampleResult(BaseModel):
    """Evaluation results for a single sample.
    
    Attributes:
        sample: Original evaluation sample
        metrics: Dictionary of metric results
        overall_score: Aggregated overall score
        timestamp: When the evaluation was performed
    """
    
    model_config = ConfigDict(extra="allow")
    
    sample: EvaluationSample = Field(..., description="Original sample")
    metrics: Dict[str, MetricResult] = Field(
        default_factory=dict,
        description="Metric results"
    )
    overall_score: Optional[float] = Field(None, description="Overall aggregated score")
    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="Evaluation timestamp"
    )


class RAGDataset(BaseModel):
    """Collection of RAG evaluation samples.
    
    Attributes:
        samples: List of RAG evaluation samples
        metadata: Dataset-level metadata
        name: Dataset name
        version: Dataset version
    """
    
    model_config = ConfigDict(extra="allow")
    
    samples: List[RAGSample] = Field(
        ...,
        description="List of RAG evaluation samples"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Dataset metadata"
    )
    name: Optional[str] = Field(None, description="Dataset name")
    version: Optional[str] = Field(None, description="Dataset version")
    
    @field_validator("samples")
    @classmethod
    def validate_samples(cls, v: List[RAGSample]) -> List[RAGSample]:
        """Validate samples list is not empty."""
        if not v:
            raise ValueError("Dataset must contain at least one sample")
        return v
    
    def __len__(self) -> int:
        """Return number of samples."""
        return len(self.samples)
    
    def __getitem__(self, idx: int) -> RAGSample:
        """Get sample by index."""
        return self.samples[idx]
    
    def __iter__(self):
        """Iterate over samples."""
        return iter(self.samples)


# Alias for backward compatibility
EvaluationDataset = RAGDataset


class EvaluationResults(BaseModel):
    """Complete evaluation results for a dataset.
    
    Attributes:
        dataset_name: Name of evaluated dataset
        results: List of sample results
        aggregated_metrics: Aggregated metrics across all samples
        metadata: Evaluation metadata (config, timestamp, etc.)
        summary: Human-readable summary
    """
    
    model_config = ConfigDict(extra="allow")
    
    dataset_name: Optional[str] = Field(None, description="Dataset name")
    results: List[SampleResult] = Field(
        default_factory=list,
        description="Individual sample results"
    )
    aggregated_metrics: Dict[str, Dict[str, float]] = Field(
        default_factory=dict,
        description="Aggregated metrics"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Evaluation metadata"
    )
    summary: Optional[str] = Field(None, description="Evaluation summary")
    timestamp: datetime = Field(
        default_factory=datetime.utcnow,
        description="Evaluation timestamp"
    )
    
    def get_metric_scores(self, metric_name: str) -> List[float]:
        """Extract all scores for a specific metric.
        
        Args:
            metric_name: Name of the metric
            
        Returns:
            List of scores for the metric
        """
        scores = []
        for result in self.results:
            if metric_name in result.metrics:
                metric_result = result.metrics[metric_name]
                if metric_result.score is not None:
                    scores.append(metric_result.score)
        return scores
    
    def get_pass_rate(self, metric_name: str) -> float:
        """Calculate pass rate for a specific metric.
        
        Args:
            metric_name: Name of the metric
            
        Returns:
            Pass rate (0-1)
        """
        total = 0
        passed = 0
        for result in self.results:
            if metric_name in result.metrics:
                metric_result = result.metrics[metric_name]
                if metric_result.passed is not None:
                    total += 1
                    if metric_result.passed:
                        passed += 1
        return passed / total if total > 0 else 0.0
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert results to dictionary."""
        return self.model_dump()

    def save_json(self, path: Union[str, Path], indent: int = 2) -> None:
        """Save results to a JSON file."""
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(self.model_dump(), f, indent=indent, ensure_ascii=False, default=str)
    
    def summary_text(self) -> str:
        """Generate human-readable summary.
        
        Returns:
            Formatted summary string
        """
        lines = [
            f"Evaluation Results: {self.dataset_name or 'Unknown'}",
            f"Timestamp: {self.timestamp.isoformat()}",
            f"Total Samples: {len(self.results)}",
            "",
            "Aggregated Metrics:",
        ]
        
        for metric_name, stats in self.aggregated_metrics.items():
            lines.append(f"  {metric_name}:")
            for stat_name, value in stats.items():
                lines.append(f"    {stat_name}: {value:.4f}")
        
        return "\n".join(lines)
